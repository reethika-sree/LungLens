MEDICAL_DISCLAIMER = (
    "Medical Disclaimer: This preliminary risk assessment is generated by an AI screening model using reported symptoms. "
    "It does not replace professional medical judgment or provide a confirmed diagnosis of Tuberculosis. "
    "Please visit your nearest Primary Health Centre (PHC) for confirmatory diagnostic testing (Sputum Smear Microscopy, CBNAAT/GeneXpert, or Chest X-ray)."
)


def get_contributing_factors(symptoms: dict) -> list[str]:
    factors = []
    cw = symptoms.get("cough_weeks")
    if isinstance(cw, (int, float)) and cw >= 2:
        factors.append(f"Persistent cough ({cw} weeks): Major cardinal symptom of pulmonary TB")
    elif symptoms.get("cough_weeks") == "mentioned_unknown_duration":
        factors.append("Active cough reported: Clinical screening criterion for TB triage")

    if symptoms.get("hemoptysis"):
        factors.append("Blood in sputum (Hemoptysis): Critical emergency red flag requiring urgent evaluation")
    if symptoms.get("night_fever"):
        factors.append("Evening/night fever: Key presumptive WHO/RNTCP clinical sign")
    if symptoms.get("weight_loss"):
        factors.append("Unexplained weight loss: Significant constitutional manifestation of chronic infection")
    if symptoms.get("night_sweats"):
        factors.append("Drenching night sweats: Characteristic B-symptom")
    if symptoms.get("dyspnea"):
        factors.append("Shortness of breath (Dyspnea): Indicates respiratory compromise")
    if symptoms.get("chest_pain"):
        factors.append("Chest pain: Pleuritic pain consistent with thoracic irritation")
    if symptoms.get("contact_tb"):
        factors.append("Household / close contact with confirmed TB case: Strong epidemiological risk factor")
    if symptoms.get("cough_phlegm"):
        factors.append("Productive wet cough: Indicates active sputum production for microscopy / GeneXpert")
    if symptoms.get("loss_appetite"):
        factors.append("Loss of appetite: Systemic constitutional symptom")
    if symptoms.get("occupation_risk"):
        factors.append("Occupational dust / silica exposure: Increases susceptibility to pulmonary tuberculosis")
    if symptoms.get("swollen_lymph"):
        factors.append("Swollen lymph nodes: Potential indicator of tuberculous lymphadenitis")
    if symptoms.get("hiv_positive"):
        factors.append("Immunocompromised status: Major risk multiplier for active TB")

    if not factors:
        factors.append("No primary high-risk TB symptoms reported.")
    return factors


